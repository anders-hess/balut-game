import assert from 'node:assert/strict';
import {initialScorecard,score,applyScore,targetColumn,totals,rng,roll,uniqueHolds,play,greedyPolicy} from './simulator.mjs';
assert.equal(score('straight',[1,2,3,4,5]),15);
assert.equal(score('straight',[2,3,4,5,6]),20);
assert.equal(score('straight',[1,1,3,4,5]),0);
assert.equal(score('fullHouse',[3,3,3,5,5]),19);
assert.equal(score('fullHouse',[3,3,3,3,5]),0);
assert.equal(score('balut',[6,6,6,6,6]),50);
assert.equal(score('balut',[6,6,6,6,5]),0);
assert.equal(targetColumn(initialScorecard(),'fours',16),3);
assert.equal(targetColumn(initialScorecard(),'fours',12),0);
assert.equal(targetColumn(initialScorecard(),'straight',20),3);
let card=initialScorecard();
card=applyScore(card,'straight',[2,3,4,5,6]).card;
assert.deepEqual(card.straight,[null,null,null,20]);
card=applyScore(card,'straight',[1,2,3,4,5]).card;
assert.deepEqual(card.straight,[15,null,null,20]);
assert.equal(totals(initialScorecard()).big,-2);
assert.equal(totals(Object.fromEntries(Object.entries(initialScorecard()).map(([c,a])=>[c,a.map(()=>0)]))).big,-2);
let a=rng(42),b=rng(42);assert.deepEqual(roll(a),roll(b));
assert.equal(uniqueHolds([1,3,4,4,5]).length,24);
const x=play(123,greedyPolicy),y=play(123,greedyPolicy);
assert.deepEqual(x,y);
assert.equal(Object.values(x.card).flat().filter(v=>v!==null).length,28);
