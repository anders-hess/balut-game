// Iteration 13: independent game-level train/validation/test corpus of Oracle 2.0
// optimal pre-first-roll V*(s) labels and complete present-roll Q*(s,d,a) tables.
// Real production-Oracle trajectories define *states*, never training targets.
import assert from 'node:assert/strict';
import {writeFileSync} from 'node:fs';
import {performance} from 'node:perf_hooks';
import {rng,roll,initialScorecard,applyScore,totals} from '../phase1/simulator.mjs';
import {cachedPolicy} from '../phase1/cached-oracle.mjs';
import {encodeCard,exactAtBoundary,exactAtRoll,actionRegret,ORACLE2_SOURCE_BLOB} from './adapter.mjs';
import {exactFeatures,FEATURE_VERSION,assertSeedPartition} from './features.mjs';

const n=Number(process.argv[2]??60);
const seedBase=Number(process.argv[3]??910100000);
const prefix=process.argv[4]??'oracle3-phase4-supervised';
assert.ok(Number.isInteger(n)&&n>=15&&n<=200);
assert.ok(Number.isSafeInteger(seedBase)&&seedBase>=0&&seedBase+n<2**32);
const trainCut=Math.floor(n*.6),valCut=trainCut+Math.floor(n*.2);
const nativeOptions={cap:250000,timeoutMs:12000};
function lateRoots(seed){
 const rand=rng(seed),roots=[];
 let card=initialScorecard();
 for(let turn=0;turn<28;turn++){
  let dice=roll(rand),left=2;
  const remaining=28-turn;
  let recorded=false;
  while(true){
   const action=cachedPolicy({card,dice,rollsRemaining:left,turn});
   if(remaining<=3&&!recorded){
    roots.push({seed,turn,remaining,card,dice:[...dice],rollsRemaining:left,productionAction:action});
    recorded=true;
   }
   if(action.type==='score'){card=applyScore(card,action.category,dice).card;break;}
   assert.ok(left>0,'production must not reroll with 0 rolls');
   dice=[...action.held,...roll(rand,5-action.held.length)];left--;
  }
 }
 assert.equal(encodeCard(card).remaining,0);
 assert.equal(roots.length,3);
 return roots;
}
const started=performance.now(),rows=[],failures=[],counts={};
for(let i=0;i<n;i++){
 const seed=seedBase+i,split=i<trainCut?'train':i<valCut?'validation':'test';
 for(const root of lateRoots(seed)){
  assert.equal(encodeCard(root.card).remaining,root.remaining);
  const features=exactFeatures(root.card),currentBP=totals(root.card).big;
  const boundary=exactAtBoundary(root.card,nativeOptions);
  const q=exactAtRoll(root,nativeOptions);
  const row={seed,split,remaining:root.remaining,card:root.card,features,
   dice:root.dice,rollsRemaining:root.rollsRemaining,productionAction:root.productionAction,
   currentBP,
   boundary:boundary.status==='EXACT_FLOAT64'?{
    status:'EXACT_FLOAT64',optimalFinalBP:boundary.value,
    optimalRemainingBP:boundary.value-currentBP,states:boundary.states,
    wallMs:boundary.wallMs,dpSeconds:boundary.seconds}:boundary,
   qReference:q.status==='EXACT_FLOAT64'?{
    status:'EXACT_FLOAT64',optimalFinalBP:q.value,actions:q.actions,
    states:q.states,wallMs:q.wallMs,dpSeconds:q.seconds}:q
  };
  if(q.status==='EXACT_FLOAT64')
   row.productionQRegret=actionRegret(q,root.productionAction,root.dice).regretBP;
  rows.push(row);
  const k=split+'_'+root.remaining;counts[k]??={attempted:0,boundarySolved:0,qSolved:0};
  counts[k].attempted++;
  if(row.boundary.status==='EXACT_FLOAT64')counts[k].boundarySolved++;
  else failures.push({seed,remaining:root.remaining,type:'boundary',status:boundary.status,reason:boundary.reason,stderr:boundary.stderr});
  if(row.qReference.status==='EXACT_FLOAT64')counts[k].qSolved++;
  else failures.push({seed,remaining:root.remaining,type:'q',status:q.status,reason:q.reason,stderr:q.stderr});
 }
}
const splits=assertSeedPartition(rows,seedBase,n);
const solved=rows.filter(r=>r.boundary.status==='EXACT_FLOAT64').length;
const solvedQ=rows.filter(r=>r.qReference.status==='EXACT_FLOAT64').length;
const summary={status:'RESULTS_NOT_POLICY_BENCHMARK',source:'Oracle 2.0 v46 exact reachable Bellman',
 sourceBlobSha:ORACLE2_SOURCE_BLOB,featureVersion:FEATURE_VERSION,
 seedBase,nGames:n,seedEnd:seedBase+n-1,nRoots:rows.length,
 gameSplit:splits,counts,solvedBoundary:solved,solvedQ,
 availableActionQLabels:rows.reduce((s,r)=>s+(r.qReference.actions?Object.keys(r.qReference.actions).length:0),0),
 failedLabels:failures.length,wallMs:performance.now()-started,
 peakParentRssBytes:process.memoryUsage().rss,node:process.version,
 limitations:[
  'Optimal Bellman targets only for solved 1-3-turn positions, not a full 28-turn exact strategy',
  'Native v46 labels are Float64 complete-DP results, not rational proofs',
  'All scorecards are generated by cached production policy, not uniform scorecard sampling',
  'Whole seed games preassigned to train/validation/test; do not pick an architecture based on test scores',
  'Parent RSS excludes native C++ subprocess peak; per-call wall and states are recorded',
  'Unsolved solver/time-cap cases are retained as failures and never imputed or relabeled approximate',
  'Q labels conditional on observed dice; boundary labels condition before the first roll'
 ]};
writeFileSync(prefix+'.json',JSON.stringify({summary,rows,failures},null,2)+'\n');
writeFileSync(prefix+'.collection.json',JSON.stringify(summary,null,2)+'\n');
console.log('ORACLE3_SUPERVISED_COLLECTION='+JSON.stringify(summary));
assert.ok(solved>=Math.floor(rows.length*.7),'less than 70% exact state labels; investigate solver coverage');
assert.ok(solvedQ>=Math.floor(rows.length*.7),'less than 70% exact present-Q labels');
